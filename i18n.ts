export type Locale = "en" | "ru";

export function detectLocale(): Locale {
  const lang = globalThis.document?.documentElement?.lang ?? "";
  return lang.toLowerCase().startsWith("ru") ? "ru" : "en";
}

const isMac = /Mac|iPhone|iPad/i.test(globalThis.navigator?.platform ?? globalThis.navigator?.userAgent ?? "");
const MOD = isMac ? "⌘" : "Ctrl";
const ALT = isMac ? "⌥" : "Alt";

export const modKey = (key: string) => (isMac ? `⌘${key}` : `Ctrl+${key}`);

export function t(key: I18nKey, locale: Locale = detectLocale()): string {
  const text = (locale === "ru" ? ru : en)[key];
  return text.replace(/\{mod\}/g, MOD).replace(/\{alt\}/g, ALT).replace(/⌘(?=[A-Z↵])/g, isMac ? "⌘" : "Ctrl+");
}
